export const BEAT_NPC_SPEAKER_NAMES = Object.freeze(Object.fromEntries(BEAT_NPC_PORTRAITS.map(character => [character.id, character.name])));
const normalizeName = value => String(value || '').replace(/\s+/gu, '').toLowerCase();
const charactersByName = new Map(BEAT_NPC_PORTRAITS.flatMap(character => [character.id, character.name, ...character.aliases].map(name => [normalizeName(name), character])));

export function npcPortraitCharacter(speaker) {
    return charactersByName.get(normalizeName(speaker)) || null;
}

export function resolveNpcPortrait(speaker, face = '') {
    const character = npcPortraitCharacter(speaker);
    if (!character) return null;
    const requested = String(face || '').trim();
    const isDefault = !requested || ['default', 'neutral', '默认'].includes(requested.toLowerCase());
    const selected = isDefault ? null : character.faces.find(item => [item.emotion, item.file, item.file.replace(/\.png$/i, ''), item.assetName, item.variant].includes(requested));
    const chosen = selected || character.faces[0];
    return {
        characterId: character.id, name: character.name, emotion: chosen.emotion, variant: chosen.variant,
        src: new URL('./npc-portraits/' + character.id + '/' + encodeURIComponent(chosen.file), import.meta.url).href,
        matchedFace: isDefault || Boolean(selected),
    };
}
