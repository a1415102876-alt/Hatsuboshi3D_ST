export function isBeatInteractionCue(value) { return BEAT_INTERACTION_CUE_IDS.includes(String(value || '').trim().toLowerCase()); }
export function isBeatMotionEligible(item) {
    return !BEAT_EXCLUDED_MOTION_BUCKETS.includes(item.bucket || item.catalog?.bucket)
        && !BEAT_EXCLUDED_MOTION_FAMILIES.includes(item.family || item.catalog?.family)
        && (item.scope || item.catalog?.scope) !== 'prod';
}
export function isBeatMotionCandidate(item, family) {
    const character = item?.character || item?.catalog?.character || '';
    const cue = String(family || '');
    if (!BEAT_EXCLUDED_GENERIC_FAMILIES.includes(cue) || character !== 'cmmn') return true;
    if (cue === 'yaruki') {
        const variant = item?.variant || item?.catalog?.variant || '';
        const index = item?.index || item?.catalog?.index || '';
        return Boolean(variant) || !['001', '002'].includes(String(index));
    }
    return false;
}
export function isBeatPairedCue(value) { return BEAT_PAIRED_CUE_IDS.includes(String(value || '').trim().toLowerCase()); }
export function parseBeatCueToken(value) {
    const token = String(value || '').trim();
    const paired = /^__beat-paired__([^_]+)$/u.exec(token);
    if (paired && isBeatPairedCue(paired[1])) {
        const spec = BEAT_PAIRED_CUE_SPECS[paired[1]];
        return { mode: 'paired', gesture: spec?.gesture || paired[1], face: '', beat: true,
            ...(spec ? { bodySelector: spec.selector } : {}) };
    }
    const body = /^__beat-body__([^_]+)__face__([^_]+)$/u.exec(token);
    if (body && BEAT_BODY_CUE_SPECS[body[1]] && BEAT_FACE_IDS.includes(body[2])) {
        const spec = BEAT_BODY_CUE_SPECS[body[1]];
        return { mode: 'mixed', gesture: spec.gesture, face: body[2], bodySelector: spec.selector, beat: true };
    }
    const overlay = /^__beat-overlay__([^_]+)$/u.exec(token);
    if (overlay && BEAT_OVERLAY_CUE_SPECS[overlay[1]]) {
        const spec = BEAT_OVERLAY_CUE_SPECS[overlay[1]];
        return { mode: 'additive', gesture: spec.gesture, bodySelector: spec.selector };
    }
    return null;
}
export function resolveBeatCueAlias(value, face = '') {
    const token = String(value || '').trim().toLowerCase();
    if (token === 'shy') return resolveBeatCueAlias('tereru', face);
    face = BEAT_FACE_ALIASES[String(face).trim().toLowerCase()] || face;
    if (token === 'talk') return `__beat-body__talk-neutral__face__${BEAT_FACE_IDS.includes(String(face).trim().toLowerCase()) ? String(face).trim().toLowerCase() : 'neutral'}`;
    const body = BEAT_BODY_CUE_SPECS[token];
    if (body) return `__beat-body__${token}__face__${BEAT_FACE_IDS.includes(String(face).trim().toLowerCase()) ? String(face).trim().toLowerCase() : body.defaultFace}`;
    if (BEAT_OVERLAY_CUE_SPECS[token]) return `__beat-overlay__${token}`;
    if (isBeatPairedCue(token)) return `__beat-paired__${token}`;
    return BEAT_CUE_ALIASES[token] || '说话';
}
